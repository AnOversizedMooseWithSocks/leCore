N_TOWERS = 24000
N_WAVES = 12


def fnv1a(s):
    return int(HA.fnv1a(s))


def pcg(v):
    return int(np.asarray(DT.hash32_pcg(np.uint32(v))).item())


def wave_table(name):
    """The district's plane waves. Same construction as the field demo, in 2D, from the name."""
    out = []
    h0 = fnv1a(name)
    for i in range(N_WAVES):
        h = pcg(h0 ^ ((i * 2654435761) & 0xFFFFFFFF))
        out.append(dict(
            fx=((h & 0xFF) / 255 - 0.5) * 0.55,
            fy=(((h >> 8) & 0xFF) / 255 - 0.5) * 0.55,
            ph=((h >> 16) & 0xFFFF) / 65535 * 6.2831853,
            amp=0.35 + ((h >> 28) & 0xF) / 15 * 0.9,
        ))
    return out


def reference(name, k=64):
    """Values the page checks its own arithmetic against. A page that computes its scene from a hash
    must prove its hash is the ENGINE'S hash -- otherwise it is generating a different world that
    merely looks plausible, which is the exact bug that cost a day earlier in this arc."""
    h0 = fnv1a(name)
    return dict(name=name, fnv=h0,
                pcg=[pcg(h0 ^ i) for i in range(k)])


