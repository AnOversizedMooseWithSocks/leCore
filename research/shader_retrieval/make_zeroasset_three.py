"""Emit pages/zeroasset_three.html -- a three.js scene with ZERO downloaded scene data.

THE CLAIM, AND IT IS A BYTE COUNT. Sixteen of three.js's own examples exist to make assets smaller
or arrive sooner: Draco, KTX2, meshopt, 3D tiles, progressive LOD. Their whole subject is MOVING
BYTES. leCore's core trick is that content is a FUNCTION OF ITS NAME -- the search page ships a
6,767-term vocabulary as zero bytes, and the field demo invents a wave for a word that has never
existed. Point that at a scene and the geometry, the placement, the materials and the variation all
stop being data.

WHAT IS ACTUALLY SHIPPED: the name of the district, as a string. Everything else -- every tower's
position, height, width, rotation, colour and the coherent skyline they form -- is recomputed in the
browser from that name, bit-identically on every machine, using the ENGINE'S hash.

THE BASELINE IS THE STRONGEST HONEST ONE, not a strawman. A glTF using EXT_mesh_gpu_instancing (the
best case: one base mesh, per-instance TRS) still carries translation+rotation+scale+colour per
instance. That is what the page counts against, not an uninstanced dump.

THE SKYLINE IS A SUM OF PLANE WAVES, which is the point rather than decoration: white noise would
give a field of unrelated towers. Fractional-power encoding gives COHERENT STRUCTURE -- a dense
centre, thinning outskirts, ridges and squares -- from the same hash, which is exactly what the
field demo showed in 2D.
"""
